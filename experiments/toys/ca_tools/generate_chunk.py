#!/usr/bin/env python3
"""
generate_chunk.py
Simple generator that creates a markdown summary (chunk) for a run.
Usage:
  python3 generate_chunk.py --manifest results/ca_run_.../manifest.json --log results/.../run.log --thumbnail results/.../thumb.png --out chunk.md
"""
import argparse, json, os

p = argparse.ArgumentParser()
p.add_argument('--manifest', required=True)
p.add_argument('--log', required=False)
p.add_argument('--thumbnail', required=False)
p.add_argument('--out', default='chunk.md')
args = p.parse_args()

manifest = json.load(open(args.manifest))

lines = []
lines.append(f"# Experiment chunk: {os.path.basename(os.path.dirname(args.manifest))}\n")
lines.append('## Provenance')
lines.append('')
lines.append('```json')
lines.append(json.dumps(manifest, indent=2))
lines.append('```\n')

if args.thumbnail and os.path.exists(args.thumbnail):
    relthumb = os.path.relpath(args.thumbnail, start=os.path.dirname(args.out))
    lines.append('## Thumbnail')
    lines.append(f'![thumbnail]({relthumb})\n')

if args.log and os.path.exists(args.log):
    rel = os.path.relpath(args.log, start=os.path.dirname(args.out))
    lines.append('## Logs')
    lines.append(f'- [run.log]({rel})\n')

lines.append('## Notes')
lines.append('\n- Generated by experiments/toys/ca_tools/generate_chunk.py')

open(args.out, 'w').write('\n'.join(lines))
print('Chunk written to', args.out)
